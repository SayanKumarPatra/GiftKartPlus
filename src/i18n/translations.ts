export function translateCategoryLabel(
  name: string,
  lang: LanguageCode,
  translations?: Partial<Record<LanguageCode, LocalizedEntityText>>
): string {
  const explicit = translations?.[lang]?.name?.trim();
  if (explicit) return explicit;
  const key = name.trim().toLowerCase();
  const builtin = BUILTIN_CATEGORY_LABELS[key]?.[lang];
  if (builtin) return builtin;
  if (lang === 'bn') {
    return autoTranslateToBengali(name, 'name');
  }
  return name;
}

export function translateOccasionLabel(occasion: string, lang: LanguageCode): string {
  const key = occasion.trim().toLowerCase();
  const builtin = BUILTIN_OCCASION_LABELS[key]?.[lang];
  if (builtin) return builtin;
  if (lang === 'bn') {
    return autoTranslateToBengali(occasion, 'name');
  }
  return occasion;
}

export function getLocalizedEntityField(
  fallback: string,
  field: keyof LocalizedEntityText,
  lang: LanguageCode,
  translations?: Partial<Record<LanguageCode, LocalizedEntityText>>
): string {
  const translated = translations?.[lang]?.[field]?.trim();
  if (translated) return translated;
  if (lang === 'bn' && fallback) {
    return autoTranslateToBengali(
      fallback,
      field === 'description' || field === 'shortDescription' ? 'description' : 'name'
    );
  }
  return fallback;
}
